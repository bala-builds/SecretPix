/**
 * Toast Notification Dispatcher
 */
export function showToast(message, type = 'info', duration = 3500) {
  let container = document.getElementById('toastContainer');
  if (!container) {
    container = document.createElement('div');
    container.id = 'toastContainer';
    container.className = 'toast-container';
    document.body.appendChild(container);
  }

  const toast = document.createElement('div');
  toast.className = `toast toast-${type}`;

  const iconMap = {
    success: ICONS.CHECK,
    error: ICONS.ALERT,
    info: ICONS.INFO,
  };

  toast.innerHTML = `
    <span class="toast-icon">${iconMap[type] || ICONS.INFO}</span>
    <span class="toast-message">${escapeHtml(message)}</span>
  `;

  container.appendChild(toast);

  setTimeout(() => {
    toast.classList.add('toast-hiding');
    setTimeout(() => toast.remove(), 250);
  }, duration);
}

/**
 * View / Tab Switcher
 */
export function switchView(targetViewId) {
  // Update nav links
  document.querySelectorAll('.nav-link').forEach(link => {
    const view = link.getAttribute('data-view');
    if (view === targetViewId) {
      link.classList.add('active');
    } else {
      link.classList.remove('active');
    }
  });

  // Update views
  document.querySelectorAll('.view-section').forEach(section => {
    if (section.id === targetViewId) {
      section.classList.add('active');
    } else {
      section.classList.remove('active');
    }
  });

  // Scroll to top of content
  window.scrollTo({ top: 0, behavior: 'smooth' });
}

/**
 * Byte Formatter
 */
export function formatBytes(bytes, decimals = 1) {
  if (bytes === 0) return '0 B';
  const k = 1024;
  const dm = decimals < 0 ? 0 : decimals;
  const sizes = ['B', 'KB', 'MB', 'GB'];
  const i = Math.floor(Math.log(bytes) / Math.log(k));
  return parseFloat((bytes / Math.pow(k, i)).toFixed(dm)) + ' ' + sizes[i];
}

/**
 * Password Strength Evaluator
 */
export function evaluatePasswordStrength(password) {
  if (!password) return { score: 0, label: 'None', className: '' };

  let score = 0;
  if (password.length >= 8) score++;
  if (password.length >= 12) score++;
  if (/[A-Z]/.test(password) && /[a-z]/.test(password)) score++;
  if (/[0-9]/.test(password)) score++;
  if (/[^A-Za-z0-9]/.test(password)) score++;

  if (score <= 1) return { score: 1, label: 'Weak', className: 'weak' };
  if (score <= 3) return { score: 2, label: 'Fair', className: 'fair' };
  if (score === 4) return { score: 3, label: 'Good', className: 'good' };
  return { score: 4, label: 'Strong', className: 'strong' };
}

/**
 * Escape HTML to prevent XSS
 */
export function escapeHtml(str) {
  const div = document.createElement('div');
  div.textContent = str;
  return div.innerHTML;
}
